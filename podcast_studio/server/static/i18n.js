function i18nLang() {
  return localStorage.getItem("ps-lang") ||
    (navigator.language && navigator.language.startsWith("zh") ? "zh" : "en");
}

function t(key, fallback) {
  const dict = i18nLang() === "en" ? I18N_EN : I18N_ZH;
  return dict[key] ?? fallback ?? key;
}

function applyI18n() {
  const en = i18nLang() === "en";
  const dict = en ? I18N_EN : I18N_ZH;
  document.documentElement.lang = en ? "en" : "zh-CN";
  // 双向覆盖:en→英、zh→还原中文(否则切回中文时 DOM 里还是英文)
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const v = dict[el.dataset.i18n];
    if (v !== undefined) el.textContent = v;
  });
  document.querySelectorAll("[data-i18n-ph]").forEach((el) => {
    const v = dict[el.dataset.i18nPh];
    if (v !== undefined) el.placeholder = v;
  });
  const btn = document.getElementById("lang-toggle");
  if (btn) btn.textContent = en ? "中文" : "EN";
}

function toggleLang() {
  localStorage.setItem("ps-lang", i18nLang() === "en" ? "zh" : "en");
  applyI18n();
  if (typeof setMode === "function") setMode(currentMode);
  if (typeof loadProfiles === "function") loadProfiles().then(() => loadVoices());
  // 音色墙是动态渲染的,切换语言后按当前词典重画(数据缓存于 window.__voicesData)
  if (typeof renderVoiceWall === "function" && window.__voicesData) renderVoiceWall();
}
